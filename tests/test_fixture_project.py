"""The scaffolder's own output, checked against the rules it was built from.

`quick_tasks` was generated by `flutter-agent scaffold` and kept as a golden
project: a tasks feature that owns its data, and a settings feature that owns
none and reads `AppPreferencesCubit` from the shared package. Every rule the
agent enforces should pass on it, so a rule that starts arguing with the house
layout fails here instead of in a real app.
"""
from __future__ import annotations

from pathlib import Path

import pytest

from flutter_agent.layers import FEATURE_REQUIRED_DIRS
from flutter_agent.rules import check_path

FIXTURE = Path(__file__).parent / "fixtures" / "quick_tasks"


@pytest.fixture(scope="module")
def findings():
    assert (FIXTURE / "pubspec.yaml").is_file(), f"fixture missing at {FIXTURE}"
    found, _ = check_path(FIXTURE / "lib")
    return found


def test_the_scaffolded_project_is_clean(findings):
    assert [f.format() for f in findings] == []


def test_a_data_owning_feature_carries_every_layer(findings):
    tasks = FIXTURE / "lib/features/tasks"
    missing = [d for d in FEATURE_REQUIRED_DIRS if not (tasks / d).is_dir()]
    assert missing == []


def test_a_presentation_only_feature_carries_no_data_layer():
    """R12's reason for existing: settings reads state it does not own."""
    settings = FIXTURE / "lib/features/settings"
    assert not (settings / "data").exists()
    assert not (settings / "presentation/cubit").exists()

    body = (settings / "presentation/refactor/settings_body.dart").read_text(
        encoding="utf-8"
    )
    assert "AppPreferencesCubit" in body
